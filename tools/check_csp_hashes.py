# The shared template policy (baseline SPECIFICATION section 9), required byte for byte under /*.
SHARED_POLICY = ("default-src 'none'; script-src 'self' 'unsafe-inline' https://ajax.cloudflare.com "
                 "https://static.cloudflareinsights.com; connect-src 'self' https://cloudflareinsights.com; "
                 "style-src 'self'; font-src 'self'; img-src 'self'; base-uri 'none'; "
                 "form-action 'none'; frame-ancestors 'none'")
# The one script form a page may carry: a same-origin baseline file, written exactly as
# scripts/build-site.py writes it. Each match is taken out of the text before the page is held to
# a shape of 0 <style> and 0 <script>.
BASELINE_SCRIPT = re.compile(r'<script src="/assets/baseline/[a-z]+\.js" defer></script>')
# Baseline 1.6.0 (SPECIFICATION 7.33): the 1 script a page loads without defer, in <head> before
# the stylesheets, so a stored scheme applies before the first paint. It is taken out of the text
# only in that place and only once; anywhere else it stays, and the 0-<script> shape refuses it.
HEAD_SCRIPT = '<script data-cfasync="false" src="/assets/baseline/scheme.js"></script>'
HEAD_OPEN = re.compile(r"<head\b", re.I)
HEAD_LEFT = re.compile(r"</head\b|<body\b", re.I)
STYLESHEET = re.compile(r"""<link\b[^>]*\brel\s*=\s*["']?stylesheet\b""", re.I)
OPENER = re.compile(r"<(style|script)\b", re.I)
STYLE_ATTR = re.compile(r"\bstyle\s*=", re.I)
# P5: the literal handler accounting reads a tag roughly as HTML's tokenizer reads one IN THE DATA
# STATE, not the way html.parser does. A tag opens at `<` and an ASCII letter and runs to its `>`; an
# attribute NAME is any run of characters other than whitespace, `/`, `>` (and `=` after the first),
# with or without a value, quoted or not. So a valueless `onclick`, `onclick/`, `on-click` and
# `onload` in a tag all count, and text outside a tag ("only", "on duty") never does. It knows no
# other tokenizer state, which is why the contexts below are refused rather than read. See the
# docstring.
TAG_OPEN = re.compile(r"<[A-Za-z][^\t\n\f />]*")
TAG_ATTR = re.compile(r"[\t\n\f /]*([^\t\n\f />][^\t\n\f />=]*)"
                      r"(?:[\t\n\f ]*=[\t\n\f ]*(?:\"[^\"]*\"?|'[^']*'?|[^\t\n\f >]*))?")
TAG_CLOSE = re.compile(r"[\t\n\f /]*>?")
# Round 3 of #352: rules that do not depend on html.parser and a browser agreeing. See REFUSED
# CONTEXTS in the docstring.
VALUED_HANDLER = re.compile(r"(?i)(?<![\w-])on[\w-]*\s*=")
LEADING_DOCTYPE = re.compile(r"﻿?<!doctype html>", re.I)
MARKUP_DECL = re.compile(r"<(!--|!\[CDATA\[|!|\?)")
INERT = ("textarea", "title", "xmp", "noscript", "plaintext", "noembed", "noframes", "iframe")
INERT_OPEN = re.compile(r"<(" + "|".join(INERT) + r")(?=[\t\n\f />])", re.I)
ANY_TAG = re.compile(r"<(/?)([A-Za-z][^\t\n\f />]*)")
SVG_DIVERGENT = ("title", "desc", "foreignobject", "style", "script")
MALFORMED_END = re.compile(r"</(?![A-Za-z])")
# The ELEMENT ALLOWLIST: exactly the elements scripts/build-site.py emits (no `style`, and of the
# SVG family only `svg`, `path` and `circle`, the light and dark switch's 2 glyphs from baseline
# 1.6.0), so an element the generator never writes is refused even where the shared policy's
# 'unsafe-inline' would let a browser run what it carries. Extending the list is a reviewed change
# to the gate; see ELEMENT ALLOWLIST in the docstring.
PAGE_ELEMENTS = frozenset((
    "html", "head", "meta", "title", "link", "script", "body", "a", "header", "nav", "main",
    "footer", "section", "div", "span", "p", "h1", "h2", "h3", "em", "strong", "small", "code",
    "pre", "button", "img", "ul", "ol", "li", "table", "caption", "thead", "tbody", "tr", "th",
    "td", "svg", "path", "circle"))
# The attributes the switch's glyphs carry (SPECIFICATION 7.33: presentation attributes only, plus
# `class` and the 2 that hide a glyph from assistive technology). Any other attribute on `svg`,
# `path` or `circle` is refused, so a glyph cannot grow an href, an animation target or a style.
SVG_ELEMENTS = frozenset(("svg", "path", "circle"))
SVG_ATTRIBUTES = frozenset((
    "class", "viewbox", "width", "height", "fill", "stroke", "stroke-width", "stroke-linecap",
    "stroke-linejoin", "aria-hidden", "focusable", "d", "cx", "cy", "r"))
TAG_NAME = re.compile(r"</?([A-Za-z][^\t\n\f />]*)")
ASCII_LOWER = str.maketrans("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz")
CHARSET = re.compile(r"charset\s*=", re.I)
META_UTF8 = '<meta charset="utf-8">'
CSP = "content-security-policy"
# Row 3.18: suffixes refused under site/ in any case, with the reason a reader sees. See THE REST OF
# `site/` in the docstring.
XHTML_WHY = ("is XHTML, which a browser parses as XML and whose scripts it runs under the site's /* "
             "CSP; this gate models HTML pages and SVG documents, not XHTML, so it is refused")
COMPRESSED_WHY = ("is compressed, which this gate cannot read as text, and a host that serves "
                  "precompressed files can answer a request for the uncompressed name with it, "
                  "which the tree cannot show; ship the document uncompressed")
REFUSED = {".xhtml": XHTML_WHY, ".xht": XHTML_WHY,
           ".svgz": ("is compressed SVG, which this gate cannot read as text and a browser renders "
                     "only when the host serves it gzip-encoded; ship it as a plain .svg"),
           ".gz": COMPRESSED_WHY, ".br": COMPRESSED_WHY, ".zst": COMPRESSED_WHY}
TRAILING_DOT_WHY = ("ends with a dot, and which type a host serves such a name as, and whether it "
                    "strips the dot first, is outside this gate's site model, so it is refused")


def name_suffix(name):
    """The lower-cased text from the LAST dot of a file name, or "" when it has no dot.

    Unlike pathlib's suffix, a dotfile is its own suffix, so a file named `.svg` is an SVG and a file
    named `.xhtml` is XHTML. A name ending with a dot is refused before this is asked.
    """
    return name[name.rindex("."):].lower() if "." in name else ""
# P5: every ASCII control character and space, removed from a URL before its scheme is read. A
# superset of what a browser's URL parser strips; see SVG DOCUMENTS in the docstring.
URL_NOISE = re.compile(r"[\x00-\x20\x7f]")


class Inline(HTMLParser):
    """Collect the text of every <script> and <style>, any style= attribute and any on* attribute."""

    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.blocks = {"script": [], "style": []}
        self.attrs = {"script": [], "style": []}
        self.style_attrs = []
        self.on_attrs = []
        self.svg_attrs = []
        self.self_closing = []
        self._open = None

    def handle_starttag(self, tag, attrs):
        if any(k.lower() == "style" for k, _ in attrs):
            self.style_attrs.append((tag, self.getpos()[0]))
        for k, _ in attrs:
            if k.lower().startswith("on"):
                self.on_attrs.append((tag, k.lower(), self.getpos()[0]))
            if tag in SVG_ELEMENTS and k.lower() not in SVG_ATTRIBUTES:
                self.svg_attrs.append((tag, k.lower(), self.getpos()[0]))
        if tag in ("script", "style"):
            self._open = tag
            self.blocks[tag].append([])
            self.attrs[tag].append(([k.lower() for k, _ in attrs], self.getpos()[0]))

    def handle_startendtag(self, tag, attrs):
        # `<style/>` never enters CDATA mode in html.parser, so the element records an EMPTY body and
        # the stylesheet is parsed as markup after it. A browser ignores the self-closing flag on a
        # non-void HTML element and reads to the real `</style>`.
        if tag in ("script", "style"):
            self.self_closing.append((tag, self.getpos()[0]))
        super().handle_startendtag(tag, attrs)

    def handle_endtag(self, tag):
        if tag == self._open:
            self._open = None

    def handle_data(self, data):
        if self._open:
            self.blocks[self._open][-1].append(data)

    def bodies(self, tag):
        return ["".join(parts) for parts in self.blocks[tag]]


def normalized(data: bytes) -> str:
    """The page as a browser's tokenizer sees it: UTF-8, with CRLF and lone CR normalized to LF,
    because HTML's input-stream preprocessing normalizes them before tokenizing."""
    return data.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")


def literal_on_attrs(text):
    """How many attribute names in tag context in `text` begin with `on`, ASCII case-insensitively.

    Each tag is read from its `<` to its `>` as HTML's tokenizer reads a tag in the data state
    (TAG_OPEN, TAG_ATTR), and scanning resumes after the tag, so a `<` inside a quoted value opens
    nothing. It is NOT equivalent to the tokenizer: it has no comment, CDATA, declaration or raw-text
    state, so a fake `<b title="` inside inert text would make it swallow a real tag after it. It is
    defense in depth; unmodelled_contexts() refuses every page where that can happen.
    """
    count, pos = 0, 0
    while tag := TAG_OPEN.search(text, pos):
        pos = tag.end()
        while attr := TAG_ATTR.match(text, pos):
            pos = attr.end()
            if attr.group(1)[:2].lower() == "on":
                count += 1
    return count


def line_of(text, index):
    return text.count("\n", 0, index) + 1


def tag_end(text, pos):
    """The index just past the tag whose name ends at `pos`, read as literal_on_attrs() reads one."""
    while attr := TAG_ATTR.match(text, pos):
        pos = attr.end()
    return TAG_CLOSE.match(text, pos).end()


def outside_blocks(html, page):
    """`html` with the body of each parsed `<style>`/`<script>` blanked to its newlines alone.

    A body is located right after a bare opening tag of its kind, in any case; one that cannot be
    located is left in place, so a later rule reads more text, never less, and fails closed.
    """
    for tag in ("style", "script"):
        opener = re.compile(f"<{tag}>", re.I)
        pos = 0
        for body in page.bodies(tag):
            for m in opener.finditer(html, pos):
                if html.startswith(body, m.end()):
                    html = html[:m.end()] + "\n" * body.count("\n") + html[m.end() + len(body):]
                    pos = m.end()
                    break
    return html


def handler_advice(shape):
    """What an on* finding asks of the author, by whether the page's declared shape allows an
    inline <script> (a template page's shape allows none)."""
    if shape["script"]:
        return "Move the behaviour into the inline <script>"
    return "This page's declared shape allows no inline <script>, so remove the handler"


def valued_handlers(path, text, advice):
    """Rule 1 of REFUSED CONTEXTS: every `on...=` outside the inline blocks, whatever its context.
    `advice` is handler_advice() for the page's declared shape."""
    return [f"{path}:{line_of(text, m.start())} contains `{m.group().strip()}` outside the "
            f"inline <style> and <script> blocks, which is an on* handler attribute or text this "
            f"gate cannot tell from one, since it reads no HTML context; this gate refuses every "
            f"on* handler on a page (P5), whatever the site's script-src or script-src-attr would "
            f"let a browser do with it. {advice}, or reword the text"
            for m in VALUED_HANDLER.finditer(text)]


def unmodelled_contexts(path, text):
    """Rule 2 of REFUSED CONTEXTS: inert text holding a `<`, where the literal scan and a browser
    can disagree about where markup starts."""
    out = []
    lead = LEADING_DOCTYPE.match(text)
    for m in MARKUP_DECL.finditer(text, lead.end() if lead else 0):
        kind, start = m.group(1), m.end()
        if kind == "!--":
            end, what = text.find("-->", start), "a comment"
        elif kind == "![CDATA[":
            end, what = text.find("]]>", start), "a CDATA section"
        else:
            end, what = text.find(">", start), f"a <{kind} declaration"
        if "<" in text[start:end if end >= 0 else len(text)]:
            out.append(f"{path}:{line_of(text, m.start())} has {what} whose text contains `<`. A "
                       f"browser reads that text as inert, while this gate's literal scan may read "
                       f"a tag there and swallow real markup after it, so it is outside the gate's "
                       f"model; take the `<` out or write it as &lt;")
    for m in INERT_OPEN.finditer(text):
        name = m.group(1).lower()
        content = tag_end(text, m.end())
        nxt = text.find("<", content)
        if nxt >= 0 and not re.match(rf"</{name}[\t\n\f />]", text[nxt:], re.I):
            out.append(f"{path}:{line_of(text, m.start())} has a <{name}> whose content contains `<` "
                       f"before its </{name}>. A browser reads that content as raw text (or, in "
                       f"foreign content, as markup), and html.parser and this gate's literal scan "
                       f"may each read it another way, so it is outside the gate's model; write the "
                       f"`<` as &lt;")
    return out


def unlisted_elements(path, html, elements=PAGE_ELEMENTS):
    """ELEMENT ALLOWLIST: every `<` or `</` and an ASCII letter anywhere in the page, comments and
    attribute values included, names an element that must be in PAGE_ELEMENTS."""
    out, seen = [], set()
    for m in TAG_NAME.finditer(html):
        name = m.group(1).translate(ASCII_LOWER)
        if name not in elements and name not in seen:
            seen.add(name)
            out.append(f"{path}:{line_of(html, m.start())}: element <{name}> is not in the page "
                       f"allowlist. This gate knows how html.parser and a browser parse only the "
                       f"elements the site already uses; another one (a <frameset>, a <select>) can "
                       f"change what a browser makes of an inline block, so extending the list is a "
                       f"reviewed change to the gate, not a page edit")
    return out


def malformed_end_tags(path, html):
    """Rule 4 of REFUSED CONTEXTS: `</` without a letter after it, anywhere."""
    return [f"{path}:{line_of(html, m.start())} has a malformed end tag, `</` not followed by an "
            f"ASCII letter. In the tokenizer's data state a browser reads most such sequences as "
            f"a bogus comment running to the next `>` (`</>` is dropped, `</` at the end of input "
            f"is text, and inside script or style data, RCDATA or an attribute value it stays "
            f"text), and this gate's literal tag reading does not, so the text one swallows "
            f"(an </svg>, or "
            f"the end of an inline block) is read differently here and there. Telling the harmless "
            f"ones apart needs context this gate does not model, so it refuses every one, even "
            f"inside an inline <style> or <script>"
            for m in MALFORMED_END.finditer(html)]


def foreign_divergences(path, text):
    """Rule 3 of REFUSED CONTEXTS: foreign-content elements html.parser reads as HTML.

    Every `<svg` start tag deepens the SVG context, self-closing or not (an unquoted value can end
    in `/`), and every `</svg` read as a tag leaves it. That matches a browser only while rules 2
    and 4 hold; see rule 3 in the docstring.
    """
    out, depth, pos = [], 0, 0
    while m := ANY_TAG.search(text, pos):
        pos = tag_end(text, m.end())
        closing, name = m.group(1), m.group(2).lower()
        if name == "svg":
            depth = max(0, depth - 1) if closing else depth + 1
        elif closing:
            continue
        elif name == "math":
            out.append(f"{path}:{line_of(text, m.start())} has a <math> element. html.parser reads "
                       f"MathML as HTML, and a browser's foreign-content rules there (text and HTML "
                       f"integration points) differ, so it is outside the gate's model")
        elif depth and name in SVG_DIVERGENT:
            out.append(f"{path}:{line_of(text, m.start())} has a <{m.group(2)}> inside an inline "
                       f"<svg>. html.parser reads it as an HTML element (a <title> as RCDATA, a "
                       f"<style> or <script> as a block) where a browser reads SVG foreign content, "
                       f"so it is outside the gate's model")
    return out


def parse_page(html):
    """Parsed inline blocks and style attributes. Lenient by design; simple_enough refuses."""
    p = Inline()
    p.feed(html)
    p.close()
    return p


def simple_enough(path, page, html, shape, elements=PAGE_ELEMENTS):
    """Reasons this page is outside the shape the gate models. See the docstring."""
    out = []
    for tag, line in page.self_closing:
        out.append(f"the <{tag}> at {path}:{line} is written self-closing. html.parser reads that as "
                   f"an empty element and a browser reads to the real </{tag}>, so the block text "
                   f"this gate reads and its accounting would not match what a "
                   f"browser reads; write it with a separate closing tag")
    if CHARSET.search(html.replace(META_UTF8, "", 1)) or META_UTF8 not in html:
        out.append(f"{path} does not declare exactly one {META_UTF8}, and this gate always decodes "
                   f"UTF-8; a different declared charset would make a browser decode other bytes, "
                   f"so the text this gate reads would not match a browser's")
    # The page with its block bodies blanked, for the NUL check and REFUSED CONTEXTS below.
    outside = outside_blocks(html, page)
    if "\x00" in html:
        in_block = any("\x00" in b for tag in ("style", "script") for b in page.bodies(tag))
        if in_block:
            out.append(f"{path} contains a NUL byte in the text of an inline <style> or <script>, "
                       f"which a browser's tokenizer replaces with U+FFFD and this gate would not, "
                       f"so the block text it reads would not match a browser's")
        # A NUL in no parsed body is in the blanked text; `not in_block` keeps a finding either way.
        if "\x00" in outside or not in_block:
            out.append(f"{path} contains a NUL byte outside any inline block, where this gate does "
                       f"not model what a browser's tokenizer does with one, so it refuses every one")
    for tag in ("style", "script"):
        bodies = page.bodies(tag)
        if len(bodies) != shape[tag]:
            out.append(f"the page {path} has {len(bodies)} <{tag}> elements and this gate models "
                       f"exactly {shape[tag]} <{tag}> for this page, which is declared to carry "
                       f"none")
            continue
        for names, line in page.attrs[tag]:
            if names:
                out.append(f"the <{tag}> at {path}:{line} carries attributes ({', '.join(names)}), "
                           f"and whether a browser runs an element with them depends on rules this "
                           f"gate does not model")
    # REFUSED CONTEXTS (round 3 of #352): none of these asks html.parser anything, so a page where
    # the parser and a browser disagree cannot hide a handler from all of them at once.
    out += valued_handlers(path, outside, handler_advice(shape))
    out += unmodelled_contexts(path, outside)
    out += foreign_divergences(path, outside)
    out += malformed_end_tags(path, html)
    out += unlisted_elements(path, html, elements)
    # A literal `style=` the parser never reported is the same blind spot as an unreported element:
    # a style attribute smuggled through <svg><title> is invisible to html.parser and may still
    # reach a browser as an attribute; this gate refuses it either way.
    in_body = sum(len(STYLE_ATTR.findall(b))
                  for tag in ("style", "script") for b in page.bodies(tag))
    if len(STYLE_ATTR.findall(html)) != len(page.style_attrs) + in_body:
        out.append(f"the page {path} contains literal `style=` text this gate cannot account for; a "
                   f"style attribute the parser did not report, such as one inside <svg> or <title>, "
                   f"may still reach a browser as an attribute, and this gate refuses every style= "
                   f"attribute on a page")
    # The same accounting for an event-handler attribute (P5): a handler smuggled through
    # <svg><title> is invisible to html.parser and may still reach a browser as an attribute; this
    # gate refuses it either way.
    in_body = sum(literal_on_attrs(b) for tag in ("style", "script") for b in page.bodies(tag))
    total = literal_on_attrs(html)
    accounted = len(page.on_attrs) + in_body
    if total != accounted:
        if total > accounted:
            why = ("the literal scan found more, so one may be an attribute html.parser did not "
                   "report (inside <svg> or <title>, for example)")
        else:
            why = ("html.parser reported more, so the literal scan missed one (a real tag it read "
                   "as the quoted value of fake markup in a comment, for example)")
        out.append(f"the page {path} contains {total} literal on* attribute names in tags and this "
                   f"gate accounts for {accounted} on* handler attributes; {why}, and this gate "
                   f"refuses every on* handler on a page (P5) and every page whose two counts "
                   f"differ")
    for script in page.bodies("script"):
        if "<!--" in script:
            out.append(f"the inline <script> in {path} contains `<!--`. This gate refuses every "
                       f"`<!--` in an inline script, harmless or not, because `<!--` opens HTML's "
                       f"script-data escape states and this gate does not model them, so it cannot "
                       f"tell whether a browser ends the script at the </script> this parser does")
            break
    # Every literal opener has to be one of the declared elements or text inside one of them. This is
    # what catches an element the parser never reported: a <style> or <script> inside <svg><title> is
    # swallowed as RCDATA and produces no start tag at all, and it is live in a browser.
    inside = sum(len(OPENER.findall(b)) for tag in ("style", "script") for b in page.bodies(tag))
    total = len(OPENER.findall(html))
    expected = len(page.bodies("style")) + len(page.bodies("script")) + inside
    if total != expected:
        out.append(f"the page {path} contains {total} literal <style or <script openers and this gate "
                   f"accounts for {expected}; one of them is somewhere the parser did not report an "
                   f"element, such as inside <svg>, <title> or a comment, and a browser may well run it")
    return out


def site_pages(root):
    """Every `.html` or `.htm` (any case) under site/, as a path relative to root. The walk in
    inspect_site() has already refused any link, so a plain rglob sees only real entries."""
    base = root / SITE
    if not base.is_dir():
        return []
    return sorted(p.relative_to(root) for p in base.rglob("*")
                  if p.is_file() and name_suffix(p.name) in (".html", ".htm"))


def head_script(path, html):
    """(html with the 1 accepted HEAD_SCRIPT taken out, findings). See the docstring.

    The first HEAD_SCRIPT is taken out when the text before it opens <head> once and holds no
    </head>, no <body> and no stylesheet link; otherwise it stays in the text. A second one always
    stays. Either way what stays is refused again by the 0-<script> shape.
    """
    at = html.find(HEAD_SCRIPT)
    if at < 0:
        return html, []
    before = html[:at]
    if len(HEAD_OPEN.findall(before)) != 1 or HEAD_LEFT.search(before) or STYLESHEET.search(before):
        return html, [f"{path}:{line_of(html, at)}: the scheme.js script is not in <head> before the "
                      f"first stylesheet. This gate accepts that 1 script without defer only there "
                      f"(baseline SPECIFICATION 7.33), where it applies a stored scheme before the "
                      f"first paint"]
    rest = html[:at] + html[at + len(HEAD_SCRIPT):]
    again = rest.find(HEAD_SCRIPT)
    if again >= 0:
        return rest, [f"{path}:{line_of(rest, again)}: the scheme.js script is loaded more than "
                      f"once. This gate accepts exactly 1 script without defer on a page (baseline "
                      f"SPECIFICATION 7.33)"]
    return rest, []


def page_findings(path, html):
    """Reasons a page is outside the template page model. See the docstring.

    The 1 scheme.js head script, written exactly as HEAD_SCRIPT in <head> before the first
    stylesheet, and each same-origin baseline script, written exactly as BASELINE_SCRIPT, are taken
    out of the text (their lines are kept), and what remains must carry no `<style>` and no
    `<script>` at all, under every rule simple_enough() applies and the template element allowlist.
    """
    rest, out = head_script(path, html)
    rest = BASELINE_SCRIPT.sub("", rest)
    page = parse_page(rest)
    out += simple_enough(path, page, rest, {"style": 0, "script": 0}, PAGE_ELEMENTS)
    for tag, name, line in sorted(set(page.svg_attrs)):
        out.append(f"<{tag}> at {path}:{line} carries the attribute {name}, which is not one of the "
                   f"presentation attributes the switch's glyphs carry (baseline SPECIFICATION "
                   f"7.33); this gate admits inline SVG with those attributes only")
    for tag, line in sorted(set(page.style_attrs)):
        out.append(f"<{tag}> at {path}:{line} carries a style= attribute. This gate refuses every "
                   f"style= attribute on a page, whatever the site's style-src or style-src-attr "
                   f"would let a browser do with it; move the rule into a stylesheet")
    for tag, name, line in sorted(set(page.on_attrs)):
        out.append(f"<{tag}> at {path}:{line} carries an on* handler attribute ({name}). This gate "
                   f"refuses every on* handler on a page (P5), whatever the site's script-src or "
                   f"script-src-attr would let a browser do with it; use a same-origin script file")
    return out


def all_rule_blocks(headers_text):
    """Every rule block in the file, in order, duplicates kept: (rule, [header lines]).

    A rule is a line starting in column zero; its headers are the indented lines under it. `#` is a
    comment. EVERY rule is returned, because a CSP set or detached under any path-scoped rule can
    govern the 404 page on that path.
    """
    out, rule, lines = [], None, []
    for raw in headers_text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if not raw[0].isspace():
            if rule is not None:
                out.append((rule, lines))
            rule, lines = raw.strip(), []
        elif rule is not None:
            lines.append(raw.strip())
    if rule is not None:
        out.append((rule, lines))
    return out


def header_findings(headers_text):
    """Reasons site/_headers is outside the model: one CSP, under the bare /*, exactly the shared
    policy; no detach; no X-Robots-Tag anywhere."""
    blocks = all_rule_blocks(headers_text)
    out = []
    for rule, lines in blocks:
        for line in lines:
            name = line.lstrip("!").split(":", 1)[0].strip().lower()
            if line.startswith("!") and name == CSP:
                out.append(f"{HEADERS} detaches the Content-Security-Policy under {rule}, so a "
                           f"page served under that rule has no policy at all")
            elif name == "x-robots-tag":
                out.append(f"{HEADERS} rule {rule} sets or detaches X-Robots-Tag, which reaches "
                           f"every page its rule matches; the /draft/ review page carries its own "
                           f"robots meta, and this gate models no header-level noindex")
    csps = []
    for rule, lines in blocks:
        for line in lines:
            if line.startswith("!"):
                continue
            name, sep, value = line.partition(":")
            if sep and name.strip().lower() == CSP:
                csps.append((rule, value.strip()))
    if not csps:
        out.append(f"no Content-Security-Policy header anywhere in {HEADERS}; the pages are served "
                   f"without one")
        return out
    if len(csps) > 1:
        where = ", ".join(rule for rule, _ in csps)
        out.append(f"{HEADERS} has {len(csps)} Content-Security-Policy headers ({where}), and this "
                   f"gate models exactly one Content-Security-Policy, under /*, governing every "
                   f"page")
        return out
    rule, csp = csps[0]
    if rule != "/*":
        out.append(f"the Content-Security-Policy in {HEADERS} is under the rule {rule}, which is "
                   f"not the /* rule this gate requires; an absolute-URL or path-scoped rule "
                   f"governs only some hosts or paths and leaves the 404 page uncovered on the rest")
        return out
    if "," in csp:
        # A CSP header value is a comma-separated LIST of policies and a browser enforces every one.
        out.append(f"the Content-Security-Policy value contains a comma, which makes it more than "
                   f"one policy; this gate requires exactly the shared template policy")
    elif csp != SHARED_POLICY:
        out.append(f"the Content-Security-Policy under /* is not the shared template policy of "
                   f"baseline SPECIFICATION section 9, byte for byte. It is: {csp}. The shared "
                   f"policy is: {SHARED_POLICY}")
    return out


class SVGModelError(ValueError):
    """An XML construct outside the SVG model. See SVG DOCUMENTS in the docstring."""


def local_name(name):
    """An expat name without its `namespace|` prefix, lower-cased for a case-insensitive match."""
    return name.rsplit("|", 1)[-1].lower()


def is_javascript_url(value):
    """True when any `;`-separated segment of an attribute value is a javascript: URL (P5).

    Every ASCII control character and space is removed first, a superset of the URL parser's
    stripping, and the scheme is matched case-insensitively. See SVG DOCUMENTS in the docstring.
    """
    return any(URL_NOISE.sub("", segment).lower().startswith("javascript:")
               for segment in value.split(";"))


def check_svg(path, display):
    """Reasons this SVG document is outside what the gate allows. See SVG DOCUMENTS.

    The bytes are decoded strictly as UTF-8 and handed to expat as str, which makes expat ignore
    the encoding and version the declaration names; both are therefore checked by hand, because a
    browser honours them and would decode, and run, other text than the text inspected here.
    """
    try:
        text = path.read_bytes().decode("utf-8")
    except (OSError, UnicodeError) as exc:
        return [f"{display}: cannot read SVG as UTF-8: {exc}; a document this gate cannot decode "
                f"is one it cannot prove carries no script"]
    parser = expat.ParserCreate(namespace_separator="|")
    findings = []

    def refuse(message):
        raise SVGModelError(message)

    def start_element(name, attrs):
        where = f"{display}:{parser.CurrentLineNumber}"
        local = local_name(name)
        if local == "script":
            findings.append(f"{where}: SVG contains a script element (<{name}>), and an SVG "
                            f"document under {SITE} must carry no script (row 3.18)")
        elif local == "style":
            findings.append(f"{where}: SVG contains a style element (<{name}>), and an SVG "
                            f"document under {SITE} must carry no inline style: this gate models "
                            f"no SVG stylesheet and refuses one whatever the site's style-src "
                            f"allows (P5)")
        for attr in sorted(attrs):
            local = local_name(attr)
            if local.startswith("on"):
                findings.append(f"{where}: SVG contains an on* handler attribute ({attr}), and an "
                                f"SVG document under {SITE} must carry none (row 3.18)")
            elif local == "style":
                findings.append(f"{where}: SVG contains a style attribute ({attr}) on <{name}>, "
                                f"and an SVG document under {SITE} must carry no inline style: this "
                                f"gate models no SVG style attribute and refuses one whatever the "
                                f"site's style-src allows (P5)")
            if is_javascript_url(attrs[attr]):
                findings.append(f"{where}: SVG carries a javascript: URL in {attr} on <{name}>, "
                                f"and an SVG document under {SITE} must carry none, whether in an "
                                f"href or in an animation's to, from, by or values (P5)")

    def xml_declaration(version, encoding, standalone):
        if version != "1.0":
            refuse(f"the XML declaration names version {version!r} and this gate models XML 1.0")
        if encoding is not None and encoding.lower() != "utf-8":
            refuse(f"the XML encoding declaration names {encoding!r}, and this gate reads SVG as "
                   f"UTF-8 only")

    parser.StartElementHandler = start_element
    parser.XmlDeclHandler = xml_declaration
    parser.StartDoctypeDeclHandler = lambda *args: refuse(
        "SVG document type declarations are outside this gate's model: a DTD's entities and "
        "attribute defaults can add an element or attribute the text does not show")
    parser.ProcessingInstructionHandler = lambda target, data: refuse(
        f"SVG processing instructions are outside this gate's model: <?{target}?> asks a browser "
        f"to apply a stylesheet or transform this gate does not read")
    # Unreachable while every DTD is refused above; kept so a later relaxation cannot fetch.
    parser.ExternalEntityRefHandler = lambda *args: refuse(
        "SVG external entities are outside this gate's model")
    try:
        parser.Parse(text, True)
    except (expat.ExpatError, SVGModelError) as exc:
        findings.append(f"{display}:{parser.CurrentLineNumber}: cannot inspect SVG: {exc}; a "
                        f"document this gate cannot parse is one it cannot prove carries no script")
    return findings


def inspect_site(root):
    """(findings, SVG documents inspected) over every entry under site/, following no link.

    Iterative, over lstat, so a link is seen as a link and never followed, and a metadata read or a
    directory listing that fails is a finding rather than a silent skip. See THE REST OF `site/`.
    """
    site = root / SITE
    findings, inspected, pending = [], 0, [site]
    while pending:
        path = pending.pop()
        display = path.relative_to(root)
        try:
            mode = path.lstat().st_mode
        except OSError as exc:
            findings.append(f"{display}: cannot inspect site entry: {exc}; an entry this gate "
                            f"cannot see may be a page or document it would refuse")
            continue
        if stat.S_ISLNK(mode):
            findings.append(f"{display} is a symbolic link, and symlinks are outside this gate's "
                            f"site model: a linked directory is never walked and a dangling link "
                            f"never read, so what the host serves through one would be unchecked; "
                            f"replace it with the real file or directory")
            continue
        if path.name.endswith("."):
            findings.append(f"{display} {TRAILING_DOT_WHY}")
            continue
        suffix = name_suffix(path.name)
        if suffix in REFUSED:
            findings.append(f"{display} {REFUSED[suffix]}")
            continue
        if stat.S_ISDIR(mode):
            try:
                children = sorted(path.iterdir(), reverse=True)
            except OSError as exc:
                findings.append(f"{display}: cannot enumerate site directory: {exc}; a directory "
                                f"this gate cannot list may hold a page or document it would refuse")
                continue
            pending.extend(children)
            continue
        if path == site:
            findings.append(f"{display} is not a directory, and this gate's site model needs one")
            continue
        if not stat.S_ISREG(mode):
            findings.append(f"{display} is not a regular file, and non-regular entries (a FIFO, a "
                            f"device) are outside this gate's site model; a read could block or "
                            f"return anything")
            continue
        if suffix == ".svg":
            inspected += 1
            findings += check_svg(path, display)
    return sorted(findings), inspected


def main() -> int:
    root = Path(__file__).resolve().parents[1]

    documents, inspected = inspect_site(root)
    if documents:
        for why in documents:
            print(f"  FAIL  {why}")
        return 1

    pages = site_pages(root)
    if not pages:
        print(f"  FAIL  {SITE} holds no pages; the published site is generated into it")
        return 1
    reasons = []
    for path in pages:
        try:
            reasons += page_findings(path, normalized((root / path).read_bytes()))
        except Exception as exc:
            reasons.append(f"could not read {path}: {exc}")
    if reasons:
        for why in reasons:
            print(f"  FAIL  {why}")
        return 1

    try:
        headers_text = (root / HEADERS).read_text(encoding="utf-8")
    except Exception as exc:
        print(f"  FAIL  could not read {HEADERS}: {exc}")
        return 1
    findings = header_findings(headers_text)
    if findings:
        for why in findings:
            print(f"  FAIL  {why}")
        return 1

    print(f"  ok    {len(pages)} page(s) under {SITE} carry no inline block, style= attribute or "
          f"on* handler, load scripts only as the generator's same-origin baseline forms (deferred, "
          f"and the 1 scheme.js head script), and use only the template's elements; {inspected} "
          f"SVG document(s) carry no <script>, on* handler, javascript: URL or inline style")
    print(f"  ok    {HEADERS} serves exactly the shared template policy (SPECIFICATION section 9) "
          f"under the 1 /* rule, with no other Content-Security-Policy, no detach and no "
          f"X-Robots-Tag")
    return 0


if __name__ == "__main__":
    sys.exit(main())
