#!/usr/bin/env python3
"""Check that every page under site/ fits the template page model and that site/_headers serves
exactly the shared template policy, under /* alone.

THE MODEL, SINCE PROMOTION (the owner's approval of 2026-11-03; baseline SPECIFICATION section
4.1 item 5). Every page under site/ is generated by scripts/build-site.py on the shared site
template, and a template page carries NO inline code at all:

  - no inline <style> and no inline <script>: a page's only scripts are same-origin baseline
    files, written exactly as the generator writes them, under 2 rules:
      1. THE SCHEME.JS HEAD SCRIPT (baseline 1.6.0, SPECIFICATION 7.33), read on the page as
         written. The exact line
         `<script data-cfasync="false" src="/assets/baseline/scheme.js"></script>` (HEAD_SCRIPT)
         occurs exactly once on every page, as a line of its own, and html.parser reads it as a
         start tag inside <head>: after the `<head>` start tag and before `</head>`, with only the
         doctype, whitespace and `<html>` before `<head>`, and only whitespace and `meta`, `title`
         and `link` elements before it in the head. No `link` before it has a rel which, with its
         character references decoded and case-folded, holds the token `stylesheet` anywhere in its
         whitespace-separated token list. Any other occurrence of `scheme.js`, in any case, is
         refused: as raw text, in any attribute or text (character references decoded, then read
         as a URL: every ASCII tab and newline removed and percent-encoding decoded, both repeated
         until nothing changes), in a script deferred or not, in the body or inside <svg>. Only
         the text and start tag of a copy of the line are excused from that search, because a
         copy is refused as a second copy or by its place; any other token on its line, such as
         the text after it, is searched like the rest;
      2. THE DEFERRED BASELINE SCRIPTS: `<script src="/assets/baseline/<name>.js" defer></script>`
         (BASELINE_SCRIPT), for any <name> of ASCII lower-case letters other than `scheme`, so
         scheme.js is never accepted in this form.
    Rule 1's line and each rule 2 match are taken out of the text (their lines kept) before the
    rest is held to a shape of 0 <style> and 0 <script>, so every other script, deferred or not,
    is refused. Rule 1 and the SVG CONTENT rule below read the page before anything is taken out,
    so a script that rule 2 would take out is still refused inside <svg>;
  - no style= attribute and no on* handler attribute anywhere, structural and literal: the
    structural read is html.parser's, and a literal `style=` or on* attribute name in tag context
    that the parser did not report (one smuggled through markup the parser misreads) is refused by
    the accounting rules kept from the hash model below;
  - only the elements the generator emits (PAGE_ELEMENTS), every tag name read context-free over
    the whole page, pinned to a list extending which is a reviewed change to this gate;
  - exactly one `<meta charset="utf-8">`, no NUL byte, no self-closing <style/> or <script/>.

Before promotion this gate pinned the live pages' inline blocks by hash in the CSP, then accepted
the owner's temporary A15 'unsafe-inline' policy, and modelled the staged draft under a /draft/*
rule. The hash model, the per-page block shapes, the A15 acceptance and the /draft/* rule model
left with the pages that needed them: there is no inline block anywhere to pin or permit, and the
one shared policy governs every page. What stayed is everything that still applies, below.

REFUSED CONTEXTS AND THE ELEMENT ALLOWLIST (rounds 3 to 5 of #352, kept whole). html.parser and a
browser can disagree about where markup starts, and 5 review rounds showed that disagreement
hiding a live element or handler. So, with the baseline script tags removed (rule 5 excepted,
which reads the page as written):

  1. every match of VALUED_HANDLER, `(?i)(?<![\\w-])on[\\w-]*\\s*=`, anywhere, is a finding: an
     on* handler with a value, or text this gate cannot tell from one;
  2. inert text holding a `<` is a finding: a comment, a CDATA section, a `<!` or `<?` declaration
     other than the leading `<!doctype html>`, and a `textarea`, `title`, `xmp`, `noscript`,
     `plaintext`, `noembed`, `noframes` or `iframe` element whose first `<` after its start tag
     does not begin its own end tag;
  3. foreign content html.parser reads as HTML is a finding: any `<math>`, and inside `<svg>` any
     `title`, `desc`, `foreignObject`, `style` or `script` (of the SVG family PAGE_ELEMENTS
     admits only `svg`, `path` and `circle`, the switch's 2 glyphs, so the others are refused by
     the allowlist too);
  4. a malformed end tag, `</` not followed by an ASCII letter, anywhere, is a finding: in the
     tokenizer's data state a browser reads most such sequences as a bogus comment to the next `>`,
     which this gate's literal tag reading does not model;
  5. SVG CONTENT (baseline 1.6.0), read on the page as written, before either script rule takes
     anything out: inside an inline <svg>, the only elements are `path` and `circle`. Every
     `<svg` start tag deepens the context and every `</svg` leaves it, read as rule 3 reads them,
     and every other start or end tag inside it is a finding: an `a`, `g`, `script` (a deferred
     baseline script included), `foreignObject`, `use`, `image`, `style`, `title`, another `svg`
     or any other name. Every attribute on an `svg`, `path` or `circle` must be one the switch's
     glyphs carry (SVG_ATTRIBUTES): the presentation and geometry attributes `viewBox`, `width`,
     `height`, `fill`, `stroke`, `stroke-width`, `stroke-linecap`, `stroke-linejoin`, `d`, `cx`,
     `cy` and `r`, plus `class`, `aria-hidden` and `focusable`, so a glyph cannot carry an href,
     an animation target or any other attribute the switch does not need;
  - the ELEMENT ALLOWLIST (round 5): every `<` or `</` and an ASCII letter anywhere in the page,
    comments and attribute values included, names an element that must be in PAGE_ELEMENTS. An
    unlisted name is a finding even where a browser would read it as text; that is the
    conservative direction. The switch's glyphs carry no style= or on* attribute, so they pass
    those rules unchanged: the rules read every element, SVG included, and refuse a style= or on*
    attribute on a glyph as on any element.

These refusals are this gate's own rule: whatever the policy's script-src, script-src-attr,
style-src or style-src-attr would let a browser do with an attribute, this gate refuses it. What
a finding reports is that this gate refuses what the finding names; the explanation a message
adds is the usual reason for the rule, written for the typical input, and can be narrower than
every input that triggers it.

THE REST OF `site/` (row 3.18, the maintainer's 2026-09-25 ruling, kept whole). Every entry under
site/ is walked over lstat, following no link. A suffix is the text from the LAST dot of the whole
entry name (a dotfile is its own suffix), and a name ending with a dot is refused. An `.xhtml` or
`.xht` is refused (a browser parses XHTML as XML and runs its scripts; this gate models HTML pages
and SVG documents). An `.svgz`, `.gz`, `.br` or `.zst` is refused (compressed bytes this gate
cannot read as text, and a host serving precompressed files can answer a request for the
uncompressed name with one). ANY symbolic link under site/, and site/ itself if it is one, is
refused; a FIFO or device is refused unread; a metadata read or directory listing that fails is a
finding, never a silent skip. Other regular files (`.txt`, `_headers`) are not inspected; this is
a suffix-based document gate, not content sniffing.

SVG DOCUMENTS (row 3.18 and P5, kept whole). Every `.svg` is decoded strictly as UTF-8 and parsed
with expat, namespace processing on, and fails on: any `script` element, in any case and
namespace; any attribute whose local name starts with `on`; any attribute VALUE whose
`;`-separated segments include a `javascript:` URL once every ASCII control character and space is
removed (a superset of what a browser's URL parser strips); and any `style` element or attribute.
It fails closed on anything it cannot read, decode or parse: another encoding or XML version, a
DOCTYPE, a processing instruction, or malformed XML. Presentation attributes (`fill=`, `stroke=`)
are not style and pass; the favicon uses them. A `<use>` or `<image>` reference is not fetched,
and a `data:` URL passes; the check is a structural rule, not a sanitizer.

THE HEADERS FILE IS CLOUDFLARE'S (kept whole). A rule is a line in column zero; its headers are
the indented lines under it; `#` is a comment; `! Name` DETACHES a header. This gate requires:

  - exactly ONE Content-Security-Policy across the whole file, under the BARE `/*` rule, because
    site/404.html is served as the body for any unmatched request path and Cloudflare matches
    rules against the REQUESTED URL, so a policy under any narrower rule leaves pages uncovered
    (and an absolute-URL rule is scoped to one host);
  - no rule anywhere detaches a Content-Security-Policy;
  - the policy's value is EXACTLY the shared template policy of baseline SPECIFICATION section 9
    (SHARED_POLICY), byte for byte, the same on all 6 sites. The shared policy keeps `script-src
    'unsafe-inline'` for Cloudflare's JavaScript Detections loader, which this gate's page model
    never relies on: no page carries an inline block for it to permit. A comma, which would make
    the value more than one policy, gets its own message;
  - no rule sets or detaches X-Robots-Tag: the 404 page carries its own robots meta, the live
    site carries no /draft/ page for a `/draft/*` noindex rule to cover (baseline SPECIFICATION
    section 4.1 items 0 and 2: that rule belongs on the `draft` branch), and a header-level noindex
    would silently deindex whatever its rule matches;
  - section 9's other headers (PINNED_HEADERS): X-Frame-Options, Permissions-Policy and
    Cross-Origin-Opener-Policy are each set exactly once across the whole file, under the bare
    `/*` rule, to exactly section 9's value, and no rule detaches one;
  - no rule sets or detaches a header Cloudflare sends itself (CLOUDFLARE_HEADERS):
    X-Content-Type-Options, Referrer-Policy or Strict-Transport-Security.

WHAT IT HASHES: nothing, since promotion. Pages are still read as a browser's tokenizer sees them
(bytes decoded as UTF-8 with CRLF and lone CR normalized to LF), so the text every rule reads is
the text a browser parses.

WHAT IT DOES NOT PROVE: that the policy is otherwise sound, or that the same-origin scripts are
safe. It reads no `src` or `href` targets beyond the baseline-script forms, so whether the policy
allows a page's external resources is not checked here. A document embedded with `srcdoc` inherits
a page's CSP and nothing here looks inside one; a `javascript:` URL on an HTML page is not checked
(P5 named SVG URLs and page on* attributes, not page URLs). Compression is recognised by suffix
only, so gzip bytes under another name are an uninspected regular file.
"""
